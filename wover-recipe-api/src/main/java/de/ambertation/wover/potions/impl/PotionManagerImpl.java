package de.ambertation.wover.potions.impl;

import de.ambertation.wover.events.impl.EventImpl;
import de.ambertation.wover.potions.api.BrewingBuilder;
import de.ambertation.wover.potions.api.OnBootstrapPotions;

import net.minecraft.advancements.Advancement;
import net.minecraft.advancements.AdvancementHolder;
import net.minecraft.core.Holder;
import net.minecraft.core.HolderGetter;
import net.minecraft.core.Registry;
import net.minecraft.data.recipes.RecipeOutput;
import net.minecraft.data.recipes.packs.VanillaBrewingProvider;
import net.minecraft.resources.ResourceKey;
import net.minecraft.world.item.Item;
import net.minecraft.world.item.alchemy.Potion;
import net.minecraft.world.item.crafting.Recipe;

import java.util.ArrayList;
import java.util.HashSet;
import java.util.List;
import java.util.Set;
import java.util.function.BiConsumer;
import java.util.stream.Stream;
import org.jetbrains.annotations.ApiStatus;
import org.jetbrains.annotations.Nullable;

/**
 * Runtime side of {@link de.ambertation.wover.potions.api.PotionManager#BOOTSTRAP_POTIONS}.
 * <p>
 * <b>Why this class exists in this shape.</b> Up to 26.1 brewing lived in {@code PotionBrewing}: a
 * hard-coded, non-datapack registry built once per reload by {@code PotionBrewing#bootstrap}, which is why
 * WoVer hooked it with a mixin ({@code PotionBrewingMixin}) and simply handed subscribers the vanilla
 * {@code PotionBrewing.Builder}. 26.3 deleted {@code PotionBrewing} outright and folded brewing into the
 * recipe system: a brew is now a {@code minecraft:brewing} {@link net.minecraft.world.item.crafting.Recipe}
 * ({@code BrewingRecipe}, matching a {@code BrewingInput}) that lives in the {@code minecraft:recipe}
 * datapack registry, and vanilla ships one JSON file per brew, generated by
 * {@link net.minecraft.data.recipes.BrewingProvider}. There is no builder to mix into any more.
 * <p>
 * The replacement extension point is therefore the recipe pipeline this module already owns: brewing
 * recipes contributed by subscribers are generated with vanilla's own {@code BrewingProvider} machinery and
 * injected into the live {@code RecipeMap} by
 * {@link de.ambertation.wover.recipe.impl.RecipeRuntimeProviderImpl}, right next to the recipes contributed
 * through {@code RecipeBuilder#BOOTSTRAP_RECIPES}. That keeps the event a runtime event, fired once per
 * world/reload exactly as before, so a subscriber that never runs datagen keeps working.
 * <p>
 * <b>Why vanilla's provider is subclassed instead of reimplemented.</b> {@code BrewingProvider} materializes
 * the cross products that {@code PotionBrewing} used to evaluate lazily: {@code buildMix} emits one recipe
 * per registered container, and {@code buildTransformations} emits one recipe per (container conversion,
 * potion) pair. To reproduce 26.1's behaviour - a mod mix is brewable in every vanilla container, and a mod
 * container works with every vanilla potion - the mod's contributions have to be folded into the *same*
 * provider run as vanilla's, which is what {@link WoverBrewingProvider} does. That run inevitably
 * regenerates all of vanilla's brews as well, so a second, extension-free run is used as a baseline and only
 * the difference is injected. That way a datapack that removed or replaced a vanilla brew is never silently
 * overruled.
 */
@ApiStatus.Internal
public class PotionManagerImpl {
    public static final EventImpl<OnBootstrapPotions> BOOTSTRAP_POTIONS =
            new EventImpl<>("BOOTSTRAP_POTIONS");

    /**
     * Emits the brewing recipes contributed by {@link #BOOTSTRAP_POTIONS} subscribers into {@code output}.
     * Does nothing (and does not touch vanilla's brewing generator at all) when no subscriber contributed
     * anything.
     *
     * @param output the output the additional {@code minecraft:brewing} recipes are written to
     */
    public static void bootstrapBrewingRecipes(RecipeOutput output) {
        final Recorder extensions = new Recorder();
        BOOTSTRAP_POTIONS.emit(c -> c.bootstrap(extensions));
        if (extensions.isEmpty()) return;

        // Pass 1: vanilla only. Establishes which recipe keys the vanilla brewing data already contains.
        final Set<ResourceKey<Recipe<?>>> vanillaKeys = new HashSet<>();
        new WoverBrewingProvider(
                new ForwardingRecipeOutput(output, (key, recipe) -> vanillaKeys.add(key)),
                new Recorder()
        ).buildRecipes();

        // Pass 2: vanilla + the recorded extensions, emitting only what pass 1 did not already produce.
        new WoverBrewingProvider(
                new ForwardingRecipeOutput(output, (key, recipe) -> {
                    if (!vanillaKeys.contains(key)) output.accept(key, recipe, null);
                }),
                extensions
        ).buildRecipes();
    }

    /**
     * Vanilla's brewing generator with the recorded extensions appended to each of its three phases. Order
     * matters here: {@code BrewingProvider#buildRecipes} runs {@code addContainers()},
     * {@code addContainerTransformations()}, {@code buildMixes()} and finally {@code buildTransformations()},
     * and every phase consumes what the previous ones registered.
     */
    private static final class WoverBrewingProvider extends VanillaBrewingProvider {
        private final Recorder extensions;

        private WoverBrewingProvider(RecipeOutput output, Recorder extensions) {
            super(output);
            this.extensions = extensions;
        }

        @Override
        protected void addContainers() {
            super.addContainers();
            // Appending after vanilla means vanilla's own mixes (built in buildMixes() below) are emitted
            // for mod containers too - the 26.1 behaviour, where PotionBrewing matched mixes regardless of
            // which container item held the potion.
            for (Item container : extensions.containers) addContainer(container);
        }

        @Override
        protected void addContainerTransformations() {
            super.addContainerTransformations();
            for (Recorder.ContainerRecipe r : extensions.containerRecipes) {
                addContainerTransformation(r.container(), r.reagent(), r.result());
            }
        }

        @Override
        protected void buildMixes() {
            super.buildMixes();
            for (Recorder.Mix m : extensions.mixes) buildMix(m.from(), m.reagent(), m.to());
            for (Recorder.StartMix m : extensions.startMixes) buildStartMix(m.reagent(), m.potion());
        }
    }

    /**
     * The {@link BrewingBuilder} handed to subscribers. It only records; {@link WoverBrewingProvider} replays
     * the records into the phase each of them belongs to, which is what makes the call order irrelevant to
     * subscribers (it was irrelevant with {@code PotionBrewing.Builder} too, because that one collected
     * everything into lists and resolved them in {@code build()}).
     */
    private static final class Recorder implements BrewingBuilder {
        private record ContainerRecipe(Item container, Item reagent, Item result) {
        }

        private record Mix(Holder<Potion> from, Item reagent, Holder<Potion> to) {
        }

        private record StartMix(Item reagent, Holder<Potion> potion) {
        }

        private final List<Item> containers = new ArrayList<>();
        private final List<ContainerRecipe> containerRecipes = new ArrayList<>();
        private final List<Mix> mixes = new ArrayList<>();
        private final List<StartMix> startMixes = new ArrayList<>();

        private boolean isEmpty() {
            return containers.isEmpty() && containerRecipes.isEmpty() && mixes.isEmpty() && startMixes.isEmpty();
        }

        @Override
        public void addContainer(Item container) {
            containers.add(container);
        }

        @Override
        public void addContainerRecipe(Item container, Item reagent, Item result) {
            containerRecipes.add(new ContainerRecipe(container, reagent, result));
        }

        @Override
        public void addMix(Holder<Potion> from, Item reagent, Holder<Potion> to) {
            mixes.add(new Mix(from, reagent, to));
        }

        @Override
        public void addStartMix(Item reagent, Holder<Potion> potion) {
            startMixes.add(new StartMix(reagent, potion));
        }
    }

    /**
     * A {@link RecipeOutput} that routes {@code accept(...)} to a callback while forwarding everything else
     * (the registry lookups a {@code RecipeOutput} exposes as a {@code BootstrapContextAccess} in 26.3) to a
     * real output. {@code BrewingRecipeBuilder} never asks for an advancement, so those calls just pass
     * through as well.
     */
    private record ForwardingRecipeOutput(RecipeOutput delegate, BiConsumer<ResourceKey<Recipe<?>>, Recipe<?>> sink)
            implements RecipeOutput {
        @Override
        public void accept(ResourceKey<Recipe<?>> key, Recipe<?> recipe, @Nullable AdvancementHolder advancement) {
            sink.accept(key, recipe);
        }

        @Override
        public Advancement.Builder advancement() {
            return delegate.advancement();
        }

        @Override
        public <S> HolderGetter<S> lookup(ResourceKey<? extends Registry<? extends S>> key) {
            return delegate.lookup(key);
        }

        @Override
        public <S> Stream<Holder.Reference<S>> listContextElements(ResourceKey<? extends Registry<? extends S>> key) {
            return delegate.listContextElements(key);
        }
    }
}
